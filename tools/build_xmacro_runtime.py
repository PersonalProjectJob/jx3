"""Assemble the native entry from canonical modules; no game-side include API needed."""
import argparse
from pathlib import Path

RUNTIME_MODULES = (
    "Config.lua",
    "Schools/Registry.lua",
    "Core/functions.lua",
    "Core/Macro.lua",
    "Schools/VanHoa/HoaGian.lua",
    "Macro.lua",
    "Features/KeySpam.lua",
)


def render_sources(sources):
    """Render canonical module bytes/text, allowing a caller-sanitized Config.lua."""
    parts = ["-- GENERATED by tools/build_xmacro_runtime.py. Edit canonical modules, then rebuild.\n",
             "-- One native entry avoids loader-order and duplicate-basename ambiguity.\n"]
    for name in RUNTIME_MODULES:
        source = sources[name]
        if isinstance(source, bytes):
            source = source.decode("utf-8-sig")
        source = source.lstrip("\ufeff").replace("\r\n", "\n").replace("\r", "\n")
        parts.append("\n-- BEGIN " + name + "\ndo\n" + source.rstrip() + "\nend\n-- END " + name + "\n")
    return "".join(parts)


def render_runtime(addon_dir, overrides=None):
    addon_dir = Path(addon_dir)
    sources = {name: (addon_dir / name).read_bytes() for name in RUNTIME_MODULES}
    if overrides:
        sources.update(overrides)
    return render_sources(sources)


def build_runtime(addon_dir):
    addon_dir = Path(addon_dir)
    output = addon_dir / "Runtime.lua"
    output.write_bytes(render_runtime(addon_dir).encode("utf-8"))
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--addon", type=Path, default=Path(__file__).resolve().parents[1] / "interface" / "xMacro")
    args = parser.parse_args()
    print(build_runtime(args.addon))


if __name__ == "__main__":
    main()
