"""Assemble the native entry from canonical modules; no game-side include API needed."""
import argparse
from pathlib import Path

RUNTIME_MODULES = (
    "Config.lua",
    "Schools/Registry.lua",
    "Core/functions.lua",
    "Core/Macro.lua",
    "Schools/VanHoa/HoaGian.lua",
    "Macro.lua",
    "Features/KeySpam.lua",
)


def render_sources(sources):
    """Render canonical module bytes/text, allowing a caller-sanitized Config.lua."""
    parts = ["-- GENERATED by tools/build_xmacro_runtime.py. Edit canonical modules, then rebuild.\n",
             "-- One native entry avoids loader-order and duplicate-basename ambiguity.\n",
             '''xMacro = xMacro or {}
xMacro.Runtime = {version="0.9.7", ready=false, modules={}, errors={}}
local runtimeStatus = xMacro.Runtime
local function ReportStartup(message)
    if OutputMessage then pcall(OutputMessage, "MSG_SYS", "[xMacro 0.9.7] " .. message .. "\\n") end
end
ReportStartup("Loading Runtime.lua")
local unavailableReported = false
local function UnavailableMacro()
    if not unavailableReported then
        ReportStartup("Runtime NOT_READY; see LOAD_ERROR at addon startup")
        unavailableReported = true
    end
    return false
end
-- Invalidate old public entrypoints before any module can fail during an upgrade.
macro = UnavailableMacro
''']
    for name in RUNTIME_MODULES:
        source = sources[name]
        if isinstance(source, bytes):
            source = source.decode("utf-8-sig")
        source = source.lstrip("\ufeff").replace("\r\n", "\n").replace("\r", "\n")
        parts.append("\n-- BEGIN " + name + "\ndo\nlocal function InitializeModule()\n" +
                     source.rstrip() + "\nend\nlocal ok, result = pcall(InitializeModule)\n" +
                     'runtimeStatus.modules["' + name + '"] = ok\n' +
                     'if not ok then\n    runtimeStatus.errors["' + name + '"] = tostring(result)\n' +
                     '    ReportStartup("LOAD_ERROR ' + name + ': " .. tostring(result))\nend\n' +
                     "end\n-- END " + name + "\n")
    parts.append('''
runtimeStatus.ready = true
for _, loaded in pairs(runtimeStatus.modules) do
    if not loaded then runtimeStatus.ready = false end
end
if runtimeStatus.ready then
    ReportStartup("MODULES_READY; use /script macro(\\"VH\\")")
else
    macro = UnavailableMacro
    ReportStartup("NOT_READY; combo disabled; see LOAD_ERROR above")
end
if xMacro.HoldKey and xMacro.HoldKey.uiError then
    ReportStartup("UI_ERROR: " .. xMacro.HoldKey.uiError)
end
''')
    return "".join(parts)


def render_runtime(addon_dir, overrides=None):
    addon_dir = Path(addon_dir)
    sources = {name: (addon_dir / name).read_bytes() for name in RUNTIME_MODULES}
    if overrides:
        sources.update(overrides)
    return render_sources(sources)


def build_runtime(addon_dir):
    addon_dir = Path(addon_dir)
    output = addon_dir / "Runtime.lua"
    output.write_bytes(render_runtime(addon_dir).encode("utf-8-sig"))
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--addon", type=Path, default=Path(__file__).resolve().parents[1] / "interface" / "xMacro")
    args = parser.parse_args()
    print(build_runtime(args.addon))


if __name__ == "__main__":
    main()
